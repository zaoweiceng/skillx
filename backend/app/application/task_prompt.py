def decision_prompt(context: dict, *, initial: bool) -> str:
    instructions = TASK_INSTRUCTIONS if initial else (
        "继续当前任务，以下是新观察和当前状态；旧消息与证据仍有效。"
        "goal 是当前用户目标，之前任务的 complete 不代表本轮完成。\n"
    )
    return instructions + json.dumps(
        context, ensure_ascii=False, default=str, separators=(",", ":")
    )
